/** ?type= の値（slug or 区分名）を有効な選択肢値に正規化する。無効なら空文字。 */
export function resolvePartnerTypeParam(param: string | null | undefined): string {
  if (!param) return "";
  const hit = partnerTypes.find((t) => t.slug === param || t.label === param);
  return hit ? hit.label : "";
}
