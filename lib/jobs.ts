/**
 * 拠点の1日の流れ（時刻・配送個数は 2026-10 ウィラン確認済み）。
 * 確認できていない数字は渡さない（parcels を省略すると個数は表示しない）。
 */
function baseSchedule(opts: {
  place: string;
  /** 配送する区市（配送エリアが未定の拠点は省略） */
  cities?: string;
  start: string;
  end: string;
  parcels?: string;
  /** 稼働前の新しい拠点で、配送個数がほかの拠点と同じ目安のとき */
  parcelsAsEstimate?: boolean;
  /** 終了時刻についての補足（拠点ごとの事情） */
  endNote?: string;
}): JobArea["schedule"] {
  const parcels = opts.parcels
    ? opts.parcelsAsEstimate
      ? `1日の配送個数は、ほかの拠点と同じく${opts.parcels}が目安です。`
      : `1日の配送個数は${opts.parcels}くらいです。`
    : "";
  return [
    {
      time: opts.start,
      title: "集合・積み込み",
      text: `${opts.place}に集合し、その日に配る荷物を軽バンへ積み込みます。`,
    },
    {
      time: "積み込み後",
      title: "担当エリアで配送",
      text: `${opts.cities ? `${opts.cities}の` : ""}担当エリアを回ります。${parcels}休憩は自分のタイミングで自由に取れます。`,
    },
    {
      time: opts.end,
      title: "業務終了",
      text: `終了時刻は荷物量や個人差で前後します。${opts.endNote ?? ""}早く終われば早く帰れます。`,
    },
  ];
}

