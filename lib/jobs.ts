export type AreaFaq = { q: string; a: string };

export type JobArea = {
  /** URLスラッグ（/jobs/[slug]） */
  slug: string;
  /** エリア名（画面表示用） */
  areaName: string;
  /** 短縮表記（フォーム・カード用） */
  shortName: string;
  /** H1（地域名を含む固有のもの） */
  h1: string;
  /** titleタグ */
  metaTitle: string;
  /** meta description */
  metaDescription: string;
  /** JobPosting jobLocation 用 */
  addressRegion: string;
  addressLocality: string;
  /** このエリアの日額（下限。JobPostingのbaseSalaryにも使用） */
  dailyPay: number;
  /** 日額の表示ラベル（例: 日額22,000円〜） */
  dailyPayLabel: string;
  /** 求人ごとの固有ID */
  identifier: string;
  /** エリアのイメージ写真（public/images/photos/配下・AI生成のイメージ画像） */
  image: string;
  /** 写真のalt（実写ではないため「〜のイメージ」と表記） */
  imageAlt: string;
  /**
   * 求人の初回公開日。【公開前確認事項】実際の公開日に更新すること。
   * ビルド日時で自動更新してはならない。
   */
  datePosted: string;
  /** 求人内容の最終更新日（sitemapのlastmodにも使用） */
  dateModified: string;
  /**
   * 募集期限（実際の締切が決まっている場合のみ設定。未定なら undefined）。
   * JobPosting の validThrough に使用。空欄なら出力しない。
   */
  validThrough?: string;
  /** 募集中か。false の求人は JobPosting・一覧・sitemap から除外する。 */
  isActive: boolean;
  /** 注力エリア（今月特に募集を強化しているエリア）。複数可。カード・一覧・トップで優先表示する。 */
  spotlight?: boolean;
  /** 注力エリアの補足文（事実に基づく案内。誇大・虚偽の緊急性は書かない） */
  spotlightNote?: string;
  /**
   * 拠点（集合場所）。ウィランに確認済みの、公開してよい範囲（町名・最寄り駅）だけを書く。
   * 詳しい住所は面談で案内する。未設定のエリアは「集合場所は面談時に案内」の表示になる。
   */
  base?: {
    /** 表示名（例: 品川拠点） */
    name: string;
    /** 所在地（町名まで） */
    address: string;
    /** 施設と最寄り駅からのアクセス（ウィランに確認できた拠点のみ。未確認なら省略） */
    access?: string;
    /** JobPosting の streetAddress（町名） */
    streetAddress: string;
  };
  /** 主な配送エリア（区市ごとの町名の例。ウィラン確認済み） */
  deliveryAreas?: { city: string; towns: string[] }[];
  /** 拠点の稼働状況（確認した時点を asOf に書く。変わったら更新する） */
  team?: { activeDrivers: number; openings: number; asOf: string };
  /** 拠点の1日の流れ（時刻つきの実例）。未設定なら共通の流れ（/work）だけを案内する */
  schedule?: { time: string; title: string; text: string }[];
  /** 勤務時間（拠点の実例がある場合は jobCommon より優先。募集要項・JobPosting にも使う） */
  workHours?: string;
  workHoursDetail?: string[];
  /** ドライバーの声（本人に確認済みの実際の声だけ。表記の調整以外は手を加えない） */
  voices?: { label: string; paragraphs: string[] }[];
  /** このエリアに関連する採用コラムのslug（内部リンク用） */
  relatedArticles: string[];
  /** リード文（エリア固有の本文） */
  lead: string[];
  /** このエリアで働く特徴（エリア固有） */
  features: { title: string; text: string }[];
  /** エリア固有のFAQ */
  areaFaq: AreaFaq[];
};

