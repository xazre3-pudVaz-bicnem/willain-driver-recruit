export function getJobArea(slug: string): JobArea | undefined {
  return jobAreas.find((a) => a.slug === slug);
}

/** 募集中（isActive）のエリアのみ。一覧・ItemList・sitemap・Indexing対象に使う。 */
export function getActiveAreas(): JobArea[] {
  return jobAreas.filter((a) => a.isActive);
}

/** 拠点の表記（所在地＋アクセス。アクセスが未確認の拠点は所在地のみ） */
export function baseLocationLabel(base: NonNullable<JobArea["base"]>): string {
  return base.access ? `${base.address}（${base.access}）` : base.address;
}

/** 面談で案内する内容（住所を番地まで公開している拠点は、住所を面談案内に含めない） */
export function meetingNoteFor(area: JobArea): string {
  return area.base?.exactAddress
    ? "担当エリア・案件内容の詳細は面談時にご案内します。"
    : jobCommon.meetingNote;
}

const REGION_ORDER = ["東京都", "神奈川県", "埼玉県", "千葉県"];

/** 募集中エリアの都県（例: 東京・神奈川・千葉）。拠点を増やしても表記がずれないようデータから作る */
export function recruitRegionsLabel(): string {
  const regions = new Set(getActiveAreas().map((a) => a.addressRegion));
  return REGION_ORDER.filter((r) => regions.has(r))
    .map((r) => r.replace(/[都県]$/, ""))
    .join("・");
}

/** 募集中エリアの短い表記（例: 品川・江東・葛西…） */
export function recruitAreasShortLabel(): string {
  return getActiveAreas()
    .map((a) => a.shortName)
    .join("・");
}

/** 募集中エリアを都県ごとにまとめた表記（例: 東京都の品川区・江東区…、千葉県の船橋市） */
export function recruitAreasLongLabel(): string {
  const byRegion = new Map<string, string[]>();
  for (const a of getActiveAreas()) {
    const local = a.areaName.replace(a.addressRegion, "");
    byRegion.set(a.addressRegion, [...(byRegion.get(a.addressRegion) ?? []), local]);
  }
  return REGION_ORDER.filter((r) => byRegion.has(r))
    .map((r) => `${r}の${byRegion.get(r)!.join("・")}`)
    .join("、");
}

/** エリア別の日額（高い順。例: 品川22,000円〜、船橋・…21,000円〜） */
export function payBreakdownLabel(): string {
  const byPay = new Map<number, string[]>();
  for (const a of getActiveAreas()) {
    byPay.set(a.dailyPay, [...(byPay.get(a.dailyPay) ?? []), a.shortName]);
  }
  return [...byPay.entries()]
    .sort(([a], [b]) => b - a)
    .map(([pay, names]) => `${names.join("・")}${pay.toLocaleString("ja-JP")}円〜`)
    .join("、");
}

/** 注力エリア（今月強化中・募集中のもの）。複数可・データの並び順。 */
export function getSpotlightAreas(): JobArea[] {
  return jobAreas.filter((a) => a.isActive && a.spotlight);
}

/** 注力エリアの案内文。拠点の稼働状況があればその数字から組み立てる（数字を二重管理しない） */
export function spotlightMessage(area: JobArea): string {
  const status =
    area.base && area.team
      ? area.opening
        ? `${area.base.name}は新しく開設した拠点で、オープニングメンバーを${area.team.openings}名募集しています。`
        : `${area.base.name}では現在${area.team.activeDrivers}名が稼働中で、新たに${area.team.openings}名を募集しています。`
      : "";
  return `${status}${area.spotlightNote ?? ""}`;
}

/**
 * JobPosting構造化データのdescription用テキスト。
 * 画面に表示している内容と同じデータから生成する（構造化データだけの情報を作らない）。
 */
export function buildJobDescriptionText(area: JobArea): string {
  const lines = [
    ...area.lead,
    "",
    "【仕事内容】",
    ...(area.jobDescription ?? jobCommon.jobDescription).map((d) => `・${d}`),
    ...(area.deliveryAreas?.length
      ? [
          "",
          "【主な配送エリア】",
          ...area.deliveryAreas.map((d) => `・${d.city}：${d.towns.join("、")}`),
        ]
      : []),
    ...(area.base
      ? ["", "【集合場所】", baseLocationLabel(area.base)]
      : []),
    "",
    "【契約形態】",
    `${jobCommon.contractType}`,
    "",
    "【報酬】",
    `${area.dailyPayLabel}（日額保証・週払い可能。いずれも規定あり）`,
    "",
    "【勤務時間】",
    ...(area.workHoursDetail ?? jobCommon.workHoursDetail).map((d) => `・${d}`),
    "",
    "【勤務日数】",
    `・${jobCommon.workDays}`,
    "",
    "【応募資格】",
    ...jobCommon.requirements.map((d) => `・${d}`),
    "",
    "【待遇・サポート】",
    ...jobCommon.support.map((d) => `・${d}`),
    "",
    meetingNoteFor(area),
  ];
  return lines.join("\n");
}
